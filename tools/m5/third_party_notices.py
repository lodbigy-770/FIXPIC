"""M5 – יצירת THIRD_PARTY_NOTICES.txt לאריזה: הודעות ורישיונות של כל הרכיבים בסגור התלויות, בטקסט אחד.

שימוש (בסביבה שהותקנו בה התלויות שייארזו, רצוי venv נקי ב-Windows/Python 3.14):
  python tools/m5/third_party_notices.py                       # כותב build/THIRD_PARTY_NOTICES.txt
  python tools/m5/third_party_notices.py --out X.txt --roots numpy pillow

מה נכלל: לכל חבילה בסגור: שם, גרסה, רישיון לפי המטא-דאטה, והטקסט המלא של כל קובצי הרישיון/NOTICE/THIRD-PARTY שבתוך החבילה
(טקסט זהה לטקסט שכבר הופיע מודפס פעם אחת בלבד, עם הפניה). בנוסף נכללים תמיד: הרישיון של מודל Big LaMa (`models/big-lama/LICENSE`)
והטקסטים של LGPL-3.0 ו-GPL-3.0 מ-`licenses/` (חבילות PySide6 מפנות אליהם ואינן כוללות אותם בגלגל; LGPL-3.0 מפנה ל-GPL-3.0).

מגבלות: (1) הכלי אוסף רק מה שבקובצי הרישיון של החבילות; רכיבים נארזים שלא תועדו שם לא יופיעו. (2) הסגור מחושב לפי הסביבה שבה הכלי רץ.
(3) זו אינה סקירה משפטית; ראו `docs/architecture/cleanup-ai/LICENSES-REVIEW.md`."""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import re
import sys
from importlib import metadata
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
_spec = importlib.util.spec_from_file_location("license_audit", Path(__file__).with_name("license_audit.py"))
la = importlib.util.module_from_spec(_spec)
sys.modules["license_audit"] = la
_spec.loader.exec_module(la)

LICENSE_FILE_RX = re.compile(r"(licen[sc]e|copying|notice|third[-_]?party)", re.I)
BAR = "=" * 78
DEFAULT_EXCLUDE = ("openvino-telemetry",)      # לא נארז (fixpic.spec: excludes); לשמור מסונכרן עם הקובץ


def package_texts(dist) -> list[tuple[str, str]]:
    """[(נתיב יחסי, טקסט)] לכל קובצי הרישיון של ההפצה (בלי קבצי קוד כמו `.h`/`.py`)."""
    out = []
    for f in sorted(dist.files or [], key=str):
        s = str(f)
        base = s.lower().rsplit("/", 1)[-1]
        if not LICENSE_FILE_RX.search(base) or base.endswith((".h", ".hpp", ".py", ".pyi", ".so", ".dll", ".pyd")):
            continue
        try:
            out.append((s, Path(dist.locate_file(f)).read_text(encoding="utf-8", errors="replace")))
        except OSError:
            continue
    return out


def render(pkgs, texts_for, extras: list[tuple[str, str]], warnings: list[str]) -> str:
    """`texts_for(pkg)` -> [(נתיב, טקסט)]. טקסט שחוזר (לפי hash) מודפס פעם אחת, ובמקומות האחרים יש הפניה."""
    seen: dict[str, str] = {}
    parts = [f"THIRD-PARTY NOTICES FOR FIXPIC\n{BAR}\nFIXPIC bundles or depends on the components listed below. Each component is listed with its "
             "version, the license declared in its package metadata, and the full text of the license/notice files shipped inside the package. "
             "This file is generated by tools/m5/third_party_notices.py.\n"]
    parts.append("Components:\n" + "\n".join(f"  - {p.name} {p.version}: {p.license or 'UNKNOWN'}" for p in pkgs) + "\n")
    for p in pkgs:
        parts.append(f"{BAR}\n{p.name} {p.version}\nDeclared license: {p.license or 'UNKNOWN'}" + (f" ({p.note})" if p.note else "") + f"\n{BAR}")
        files = texts_for(p)
        if not files:
            parts.append("(No license file is shipped inside this package; see licenses referenced below / the project's upstream.)")
            warnings.append(f"{p.name}: אין קובץ רישיון בחבילה")
        for path, txt in files:
            h = hashlib.sha256(txt.strip().encode("utf-8")).hexdigest()
            if h in seen:
                parts.append(f"--- {path} ---\n(identical to {seen[h]})")
            else:
                seen[h] = f"{p.name}: {path}"
                parts.append(f"--- {path} ---\n{txt.strip()}")
    for title, txt in extras:
        h = hashlib.sha256(txt.strip().encode("utf-8")).hexdigest()
        parts.append(f"{BAR}\n{title}\n{BAR}\n" + (f"(identical to {seen[h]})" if h in seen else txt.strip()))
    return "\n\n".join(parts) + "\n"


def default_extras() -> list[tuple[str, str]]:
    extras = []
    for title, rel in (("Big LaMa model (models/big-lama/LICENSE): Apache-2.0", "models/big-lama/LICENSE"),
                       ("GNU Lesser General Public License v3.0 (applies to PySide6 / shiboken6 / Qt)", "licenses/LGPL-3.0.txt"),
                       ("GNU General Public License v3.0 (referenced by the LGPL-3.0 text above)", "licenses/GPL-3.0.txt")):
        p = REPO / rel
        if not p.is_file():
            raise SystemExit(f"חסר קובץ רישיון נדרש: {rel}")
        extras.append((title, p.read_text(encoding="utf-8", errors="replace")))
    return extras


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--pyproject", type=Path, default=REPO / "pyproject.toml")
    ap.add_argument("--roots", nargs="+")
    ap.add_argument("--out", type=Path, default=REPO / "build" / "THIRD_PARTY_NOTICES.txt")
    ap.add_argument("--exclude", nargs="*", default=list(DEFAULT_EXCLUDE), help="חבילות שלא נארזות ולא ייכללו (ברירת מחדל: openvino-telemetry)")
    a = ap.parse_args(argv)
    roots = a.roots or la.root_requirements(a.pyproject)
    pkgs, warnings = la.collect(roots)
    pkgs = [p for p in pkgs if la.canon(p.name) not in {la.canon(e) for e in a.exclude}]
    text = render(pkgs, lambda p: package_texts(metadata.distribution(p.name)), default_extras(), warnings)
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(text, encoding="utf-8")
    print(f"נכתב {a.out}: {len(pkgs)} חבילות, {len(text) / 1024:.0f}KB, Python {sys.version.split()[0]} {sys.platform}")
    for w in warnings:
        print("אזהרה:", w, file=sys.stderr)
    return 0


if __name__ == "__main__":
    for _s in (sys.stdout, sys.stderr):          # קונסולת Windows (cp1252) לא מקודדת עברית
        if hasattr(_s, "reconfigure"):
            _s.reconfigure(encoding="utf-8", errors="replace")
    sys.exit(main())
